export function mergePilotProducts(products: GrassProduct[]): GrassProduct[] {
  const pilotSlugs = new Set(pilotProducts.map((product) => product.slug));
  return [...products.filter((product) => !pilotSlugs.has(product.slug)), ...pilotProducts];
}

export function getPilotProductBySlug(slug: string): GrassProduct | null {
  return pilotProducts.find((product) => product.slug === slug) ?? null;
}
